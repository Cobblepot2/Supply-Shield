import { createHash, generateKeyPairSync, sign } from 'node:crypto';
import { writeFile } from 'node:fs/promises';

const samples = {
  'aegis-fix.min.js': '// Classroom sample: launcher startup.\n',
  'images.7fec4c32.js': '// Classroom sample: launcher images.\n',
  'FeedList.feb647c9.js': '// Classroom sample: launcher news.\n',
  'vue-bucket.min.js': '// Classroom sample: launcher interface.\n',
};
const { publicKey, privateKey } = generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
const manifest = JSON.stringify({
  release: 'nikke-classroom-1',
  files: Object.entries(samples).map(([id, text]) => ({
    id,
    sha256: createHash('sha256').update(text, 'utf8').digest('hex'),
  })),
});
const fixture = {
  samples,
  manifest,
  publicKey: publicKey.export({ type: 'spki', format: 'der' }).toString('base64'),
  signature: sign('sha256', Buffer.from(manifest), { key: privateKey, dsaEncoding: 'ieee-p1363' }).toString('base64'),
};
await writeFile(new URL('../public/fixture.js', import.meta.url),
  '// Generated by scripts/make-fixtures.mjs from classroom-only data.\n' +
  'export const fixture = ' + JSON.stringify(fixture, null, 2) + ';\n');
